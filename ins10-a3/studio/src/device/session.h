// The conversation with one board: framing, the command queue, stream delivery and
// the board's temporary state.
//
// - One command is in flight at a time. Its reply is every line up to OK or ERR;
//   stream records arriving in between go to the streams, not to the reply.
// - Stream records are delivered in batches (every few tens of milliseconds), in the
//   order they arrived.
// - The session owns the board's temporary settings: it remembers the $ATT rate the
//   board had when we connected ("the owner's rate"), sets its own rate for viewing,
//   switches the owner's rate back in for every 'cal save' (which stores the current
//   rate as the power-up rate), and on disconnect stops the raw, mag and baro streams
//   and restores the owner's rate.
//
// A DeviceSession lives in one thread; use DeviceController from the GUI.
#pragma once

#include "core/protocol.h"
